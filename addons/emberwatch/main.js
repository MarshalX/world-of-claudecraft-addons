/// <reference types="@woc-addons/types" />

// Emberwatch: say which effect on which unit is worth knowing about, and get a tile, a
// cue and a banner when it happens.
//
// The model is the aura LIST, never the aura event. An event carries an id, a source and a
// stack count only on the application path, so a fade usually says nothing where its gain
// said plenty; `world.aurasOn` and `world.partyAuras` carry all four on every row. Nothing
// here subscribes to an aura event. The one thing only an event carries is `refresh`, so a
// tracker counting gains against fades cannot be built on a list; this one reads the
// remaining instead, where a re-application shows as a figure that went back up.
//
// The clock is `woc.onFrame` and the two aura watch keys are deliberately not subscribed:
// `world.on('auras')` signs by id and caster rather than stack count, neither key fires as
// a remaining ticks down, and a party row has no watch key at all. `characterKey` IS
// subscribed, since the rule set and the stored rows belong to one character and the game
// swaps characters inside one page load.
//
// A party row carries an id, a kind and a whole-second remaining, and nothing else: no
// source, so a rule's `mine` clause is DROPPED rather than ignored; no duration, so no
// sweep; no stacks; no school, so `world.dispellable` refuses it. Rows are read anyway,
// because one exists for a member on the far side of the map where an entity does not.
//
// Polarity goes through `world.harmful` rather than arithmetic here: a party row's `neg`
// flag is a sign test on magnitude alone, so a dot, a root, a stun and a silence all
// arrive without it.
//
// What cannot be built, and the pane says so in words: how much damage a control will take
// before it breaks. The soak and the per-hit chance never leave the server, and the wire
// carries a bare presence marker in a field the published `Aura` does not declare.
//
// An effect has its OWN painting where the game ships one, which it did not before game
// 0.39.0: that release added an aura art manifest covering the effects no ability names, the
// mob families among them, and `woc.ui.icon.aura` reads it. What is still true is that the
// family is closed and small, so most of what lands on a unit resolves through nothing: the
// game composites the rest at run time, and the only ability file to point at is filed per
// player class. What a mob does have is a PORTRAIT, so a square with no painting of its own
// carries the face of whatever applied the effect, said out loud in the tooltip and in the
// accessible name rather than left to be read off the picture.
//
// `world.abilities` is deliberately not consulted for a name. An entity's aura carries one
// on the wire; a party row carries none, and a spellbook would answer for your own kit and
// guess the rest, which is a label authoritative on one row and a guess on the next.
//
// The starter table is game content in `rules.json`, generated by `generate.mjs` beside
// this file. `woc.data` hands back `unknown`, so every row goes through `readRule` before
// it can fire anything.

const RULES_FILE = 'rules.json';
const STORE_ROWS = 'rows';
const STORE_OFF = 'disabled';

const DECIMALS = 1;
/** A faded alert has no aura left to count down, so it comes down on a clock. */
const FADED_LINGER_MS = 4000;
/** Starting square and floor. Larger than the kit's 40: this is read at a glance mid-fight. */
const TILE_FLOOR = 48;
/** Stated so a drag can solve back for the square. */
const CAPTION_HEIGHT = 15;
const CAPTION_FONT = 11;
const STRIP_WIDTH = 420;
const DEFAULT_STACK_THRESHOLD = 2;
const SINGLE_STACK = 1;
const PANE_WIDTH = 460;
const PANE_HEIGHT = 380;
const PANE_MIN_WIDTH = 280;
const PANE_MIN_HEIGHT = 190;

/** Drawn in the pane: an engine that alerts on control and stays quiet about this reads as denying it. */
const PANE_NOTES = [
  'A party row carries an id, a kind and whole seconds. No source, so "only mine" is dropped; no duration, so there is no sweep; no stacks; and removability cannot be answered at all.',
  'Nothing here can tell you how much damage a control will take before it breaks. The soak and the per-hit chance stay on the server, and the wire carries only a marker that a soak exists rather than what it is.',
];

const CONDITIONS = ['gained', 'faded', 'stacks', 'expiring'];
/** `party` is the group's rows, which reach across the map. */
const UNITS = ['player', 'target', 'party'];

let starter = [];
/** Whether the table arrived at all, which an empty one is not evidence of. */
let tableRead = false;
let mine = [];
let disabled = new Set();
/** The class the active set was assembled for, so a switch rebuilds it. */
let assembledFor = null;
let active = [];

/** The previous evaluation, which is the only way a fade is visible. */
let previous = new Map();
const alerts = new Map();

/** The first reading is everything already up, which would otherwise arrive as a cue per effect. */
let primed = false;

/**
 * One rule, or null. The loader only checks that `woc.data` parses, so the shape is a claim
 * checked here, and a stored row the player captured is the same kind of claim. A row naming
 * neither an aura id nor a kind nor a polarity is refused: it would fire on everything.
 */
function readRule(value) {
  if (typeof value !== 'object' || value === null) {
    return null;
  }
  const { id, label, unit, on } = value;
  const identified = typeof id === 'string' && id.length > 0 && typeof label === 'string';
  const described = identified && label.length > 0;
  if (!(described && UNITS.includes(unit) && CONDITIONS.includes(on))) {
    return null;
  }
  const rule = { id, label, unit, on, ...optionalOf(value) };
  if (rule.auraId === null && rule.kind === null && rule.harmful === null) {
    return null;
  }
  return rule;
}

function optionalOf(value) {
  return {
    forClass: stringOr(value.class, 'any'),
    auraId: stringOr(value.auraId, null),
    kind: stringOr(value.kind, null),
    mine: flagOr(value.mine),
    harmful: flagOr(value.harmful),
    removable: flagOr(value.removable) === true,
    bout: flagOr(value.bout) === true,
    banner: flagOr(value.banner) === true,
    cue: stringOr(value.cue, null),
    threshold: numberOr(value.threshold),
  };
}

function stringOr(value, fallback) {
  if (typeof value === 'string' && value.length > 0) {
    return value;
  }
  return fallback;
}

function flagOr(value) {
  if (typeof value === 'boolean') {
    return value;
  }
  return null;
}

function numberOr(value) {
  if (typeof value === 'number' && Number.isFinite(value)) {
    return value;
  }
  return null;
}

/** A bad row is skipped with a warning rather than the whole list being thrown away. */
function adopt(listed, source) {
  const kept = [];
  for (const [at, row] of listed.entries()) {
    const rule = readRule(row);
    if (rule === null) {
      woc.warn(`${source}: entry ${String(at)} is not a rule, leaving it out`, row);
    } else {
      kept.push(rule);
    }
  }
  return kept;
}

function readFile(file) {
  if (typeof file !== 'object' || file === null || file.format !== 'emberwatch-rules') {
    return null;
  }
  if (!Array.isArray(file.rules)) {
    return null;
  }
  return file.rules;
}

function playerClass() {
  const { player } = woc.world;
  if (player === null || player.kind !== 'player') {
    return null;
  }
  return player.templateId;
}

/** Rebuilt on a class change, never per frame. With no class only the any-class rows are in force. */
function assemble() {
  const cls = playerClass();
  if (cls === assembledFor) {
    return;
  }
  assembledFor = cls;
  active = [...starter, ...mine].filter((rule) => appliesTo(rule, cls));
}

function appliesTo(rule, cls) {
  if (disabled.has(rule.id)) {
    return false;
  }
  return rule.forClass === 'any' || rule.forClass === cls;
}

function reassemble() {
  assembledFor = false;
  assemble();
}

/**
 * The picture for an alert, and whose face it is when it is not the effect's own.
 *
 * Three routes, tried in the order the game's own resolver uses them. The effect's OWN painting
 * comes first, from the aura art manifest game 0.39.0 added: that family is exactly the effects no
 * ability id names, so a mob's aura, an encounter mechanic and a battleground rune are in it, and
 * a square filled from it needs no disclosure because it IS the effect's icon.
 *
 * The family is closed and covers a fraction of what a fight applies, so the two older routes
 * still carry most rows. Ability art is filed per player class, so an effect a mob applied
 * resolves through nothing there: the game composites those icons on a canvas from a module no
 * addon can reach, and a lockout id 404s. A mob's PORTRAIT is a file, and every catalogued
 * template ships one, so the square is filled by the thing that applied the effect rather than
 * left blank. `castBy` is what makes that honest: the tooltip and the accessible name both say
 * whose face it is, because a portrait answers a different question from an ability icon and a
 * square that does not say which is a guess.
 *
 * An npc is deliberately not portrayed. The game draws a crest for one rather than a portrait, so
 * `/ui/mobs/` would 404 and the slot would go back to being empty by a longer route.
 */
function artOf(auraId, sourceId) {
  // The effect's own painting answers for whoever applied it, so this is asked before the
  // caster is even looked up: an aura in that family is the same picture on a mob, on a
  // stranger and on you.
  const own = woc.ui.icon.aura(auraId);
  if (own !== null) {
    return { art: own, castBy: null };
  }
  const caster = woc.world.entities.get(sourceId);
  if (caster === undefined) {
    return { art: null, castBy: null };
  }
  if (caster.kind === 'player') {
    return { art: woc.ui.icon.ability(auraId, caster.templateId), castBy: null };
  }
  if (caster.kind !== 'mob') {
    return { art: null, castBy: null };
  }
  return { art: woc.ui.icon.mob(caster.templateId), castBy: caster.name };
}

/** `mine` is the clause a dot tracker cannot skip. */
function queryFor(rule) {
  const query = rowQueryFor(rule);
  if (rule.mine !== null) {
    query.mine = rule.mine;
  }
  return query;
}

/**
 * A clause the rule does not carry is LEFT OUT rather than passed as null: the query filters
 * test against `undefined`, so a null reads as "match auras whose kind is null", which is none.
 */
function rowQueryFor(rule) {
  const query = {};
  if (rule.auraId !== null) {
    query.id = rule.auraId;
  }
  if (rule.kind !== null) {
    query.kind = rule.kind;
  }
  return query;
}

function keepsAura(rule, aura, hostile) {
  if (rule.harmful !== null && rule.harmful !== woc.world.harmful(aura)) {
    return false;
  }
  return !rule.removable || woc.world.dispellable(aura, hostile);
}

function keepsRow(rule, row) {
  if (rule.removable) {
    return false;
  }
  return rule.harmful === null || rule.harmful === woc.world.harmful(row);
}

function candidateKey(rule, unitKey, auraId, sourceId) {
  return `${rule.id}|${unitKey}|${auraId}|${String(sourceId)}`;
}

function fromAura(rule, unit, unitKey, aura) {
  return {
    key: candidateKey(rule, unitKey, aura.id, aura.sourceId),
    rule,
    unitKey,
    who: unit.name,
    entityId: unit.id,
    row: false,
    auraId: aura.id,
    name: aura.name,
    derivedName: false,
    kind: aura.kind,
    school: aura.school,
    stacks: aura.stacks ?? SINGLE_STACK,
    remaining: aura.remaining,
    duration: aura.duration,
    encounterOwned: aura.unbreakableControl === true,
    ...artOf(aura.id, aura.sourceId),
  };
}

/** Null rather than a default: the display has to tell "none on this effect" from "a row cannot say". */
function fromRow(rule, member, row) {
  const unitKey = `party:${String(member.pid)}`;
  return {
    key: candidateKey(rule, unitKey, row.id, 0),
    rule,
    unitKey,
    who: member.name,
    entityId: null,
    row: true,
    auraId: row.id,
    // `shadow_word_pain` to "Shadow Word Pain", which is a GUESS and is labelled as one.
    name: woc.fmt.titleCase(row.id),
    derivedName: true,
    kind: row.kind,
    school: null,
    stacks: null,
    remaining: row.remaining ?? null,
    duration: null,
    encounterOwned: false,
    art: null,
    castBy: null,
  };
}

/** Which way removability points: a benefit comes off a hostile, a harm off a friendly. */
function hostility(unit) {
  return unit.hostile === true;
}

function entityMatches(rule, token) {
  const unit = woc.world.unit(token);
  if (unit === null) {
    return [];
  }
  const found = [];
  for (const aura of woc.world.aurasOn(token, queryFor(rule))) {
    if (keepsAura(rule, aura, hostility(unit))) {
      found.push(fromAura(rule, unit, token, aura));
    }
  }
  return found;
}

function partyMatches(rule) {
  const found = [];
  for (const member of woc.world.party?.members ?? []) {
    for (const row of woc.world.partyAuras(member.pid, rowQueryFor(rule))) {
      if (keepsRow(rule, row)) {
        found.push(fromRow(rule, member, row));
      }
    }
  }
  return found;
}

function ruleRuns(rule) {
  if (rule.on === 'expiring' && !woc.settings.expiring) {
    return false;
  }
  return !rule.bout || woc.world.match !== null;
}

function candidatesFor(rule) {
  if (!ruleRuns(rule)) {
    return [];
  }
  if (rule.unit === 'party') {
    return partyMatches(rule);
  }
  return entityMatches(rule, rule.unit);
}

function expiryThreshold(rule) {
  return rule.threshold ?? woc.settings['expiring-seconds'];
}

function stackThreshold(rule) {
  return rule.threshold ?? DEFAULT_STACK_THRESHOLD;
}

/** `gained` holds while the effect is there, so the tile is a readout rather than a flash. */
function holds(found) {
  const { rule } = found;
  if (rule.on === 'gained') {
    return true;
  }
  if (rule.on === 'stacks') {
    return found.stacks !== null && found.stacks >= stackThreshold(rule);
  }
  if (rule.on === 'expiring') {
    return found.remaining !== null && found.remaining <= expiryThreshold(rule);
  }
  return false;
}

function fractionOf(found) {
  if (found.duration === null || found.duration <= 0 || found.remaining === null) {
    return null;
  }
  return Math.min(found.remaining / found.duration, 1);
}

function stackCount(found) {
  if (found.stacks === null || found.stacks <= SINGLE_STACK) {
    return null;
  }
  return found.stacks;
}

function toneOf(found) {
  if (found.rule.banner) {
    return 'danger';
  }
  if (found.rule.on === 'expiring') {
    return 'warn';
  }
  return 'default';
}

/** A plain emit: nothing follows this topic, so there is no ask to answer. */
function announce(found, state) {
  woc.bus.emit('alert', {
    ruleId: found.rule.id,
    unit: found.unitKey,
    auraId: found.auraId,
    state,
  });
}

function bannerFor(found) {
  woc.ui.banner(found.rule.label, {
    kind: 'danger',
    size: woc.settings['banner-size'],
    detail: `on ${found.who}`,
  });
}

/** Silent while priming, or everything already up would arrive at once as news. */
function sound(found) {
  if (!primed) {
    return;
  }
  if (found.rule.cue !== null) {
    woc.sound.play(found.rule.cue, { volume: woc.settings.volume });
  }
  if (found.rule.banner) {
    bannerFor(found);
  }
}

function lingerUntil(now, momentary) {
  if (momentary) {
    return now + FADED_LINGER_MS;
  }
  return null;
}

function raise(found, now, momentary) {
  const existing = alerts.get(found.key);
  if (existing === undefined) {
    alerts.set(found.key, { found, at: now, until: lingerUntil(now, momentary) });
    sound(found);
    announce(found, 'active');
    return;
  }
  existing.found = found;
}

function clear(key) {
  const record = alerts.get(key);
  if (record === undefined) {
    return;
  }
  alerts.delete(key);
  announce(record.found, 'cleared');
}

function collect() {
  const current = new Map();
  for (const rule of active) {
    for (const found of candidatesFor(rule)) {
      current.set(found.key, found);
    }
  }
  return current;
}

/** A fade is the previous reading minus this one: the effect is not in the reading that follows. */
function fades(current, now) {
  for (const [key, found] of previous) {
    if (found.rule.on === 'faded' && !current.has(key)) {
      raise(found, now, true);
    }
  }
}

function states(current, now) {
  for (const [key, found] of current) {
    if (found.rule.on !== 'faded' && holds(found)) {
      raise(found, now, false);
    } else {
      clear(key);
    }
  }
}

/** An effect gone between two readings is in neither loop above, and would sit there for the session. */
function orphans(current) {
  for (const [key, record] of alerts) {
    if (record.until === null && !current.has(key)) {
      clear(key);
    }
  }
}

function retire(now) {
  for (const [key, record] of alerts) {
    if (record.until !== null && now >= record.until) {
      clear(key);
    }
  }
}

function evaluate(now) {
  assemble();
  const current = collect();
  states(current, now);
  orphans(current);
  fades(current, now);
  retire(now);
  previous = current;
  primed = woc.world.player !== null;
}

