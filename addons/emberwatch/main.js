function stripHeight(size) {
  return size + CAPTION_HEIGHT;
}

let tileSize = TILE_FLOOR;

/** Bare, since the tiles are the display. The title survives as the label unlock mode shows. */
const frame = woc.ui.frame({
  id: 'alerts',
  title: 'Emberwatch',
  width: STRIP_WIDTH,
  // Stated because a content-sized frame is never given a box, so there would be nothing to drag.
  height: stripHeight(TILE_FLOOR),
  density: 'bare',
  save: true,
  resizable: true,
  toggleKey: 'toggle',
  // Constants, never the current alert count: that would trap a player who sized it during a pull.
  minWidth: TILE_FLOOR,
  minHeight: stripHeight(TILE_FLOOR),
  onMove: (box) => {
    resize(box.h);
  },
});
frame.body.appendChild(list);
list.appendChild(overflow);

/** The floor is applied here as well as declared, since a box also arrives from a restore or a clamp. */
function resize(height) {
  // One unit under a fixed band, which is what `extra` is for: the caption is space the
  // square never gets, and the floor holds for a box from anywhere.
  tileSize = woc.ui.units(height, { extra: CAPTION_HEIGHT, min: TILE_FLOOR });
}

/** Read back off the element rather than held beside it: a pin and its cell share the one element. */
function sizeCell(cell) {
  const width = `${String(tileSize)}px`;
  if (cell.el.style.width === width) {
    return;
  }
  cell.el.style.width = width;
  cell.ui.update({ size: tileSize });
}

/** Which reading this came off, which is what a player checks a gap against. */
function sourceLine(found) {
  if (found.row) {
    return {
      text: 'Read off a party row: whole seconds, no stacks, no source, and at most eight effects.',
      tone: 'warn',
    };
  }
  return { text: 'Read off the unit itself.', tone: 'muted' };
}

function conditionLine(found) {
  const { rule } = found;
  if (rule.on === 'stacks') {
    return `Fires at ${String(stackThreshold(rule))} applications or more.`;
  }
  if (rule.on === 'expiring') {
    return `Fires with ${String(expiryThreshold(rule))}s or less left.`;
  }
  if (rule.on === 'faded') {
    return 'Fires when the effect goes.';
  }
  return 'Fires while the effect is there.';
}

function remainingLine(found) {
  if (found.remaining === null) {
    return { text: 'No remaining time on this reading.', tone: 'warn' };
  }
  return `${found.remaining.toFixed(DECIMALS)}s left.`;
}

function extraLines(found) {
  const lines = [];
  if (found.castBy !== null) {
    lines.push({
      text: `Pictured: ${found.castBy}, which applied it. A mob's effect has no icon of its own.`,
      tone: 'muted',
    });
  }
  if (found.encounterOwned) {
    lines.push({ text: 'The encounter owns this one: nothing you do breaks it.', tone: 'danger' });
  }
  if (found.derivedName) {
    lines.push({
      text: `Name derived from "${found.auraId}", not read from the wire.`,
      tone: 'muted',
    });
  }
  if (found.rule.unit === 'party' && found.rule.mine !== null) {
    lines.push({ text: '"Only mine" was dropped: a party row carries no source.', tone: 'warn' });
  }
  return lines;
}

/** A function, so it answers with what is left NOW rather than at the moment the tile was built. */
function tooltipFor(key) {
  const record = alerts.get(key);
  if (record === undefined) {
    return 'This alert has gone.';
  }
  const { found } = record;
  return {
    title: found.name,
    icon: found.art,
    lines: [
      `${found.rule.label}, on ${found.who}`,
      conditionLine(found),
      remainingLine(found),
      ...extraLines(found),
      sourceLine(found),
    ],
  };
}

function createCell(found) {
  const tile = woc.ui.tile({ label: labelFor(found), className: 'woc-ew-tile' });
  const el = document.createElement('div');
  el.className = 'woc-ew-cell';
  el.dataset.alert = found.key;
  el.style.display = 'flex';
  el.style.flexDirection = 'column';
  el.style.alignItems = 'center';
  // A flex item shrinks by default, so a narrowed strip would squash the squares out of true.
  el.style.flexShrink = '0';
  const caption = document.createElement('span');
  caption.className = 'woc-ew-caption';
  caption.style.overflow = 'hidden';
  caption.style.textOverflow = 'ellipsis';
  caption.style.whiteSpace = 'nowrap';
  caption.style.maxWidth = '100%';
  caption.style.fontSize = `${String(CAPTION_FONT)}px`;
  // Both directions, because the drag solves the strip's height back for the square.
  caption.style.height = `${String(CAPTION_HEIGHT)}px`;
  caption.style.lineHeight = `${String(CAPTION_HEIGHT)}px`;
  el.append(tile.el, caption);
  const cell = {
    ui: tile,
    el,
    caption,
    destroy: () => {
      tile.destroy();
      el.remove();
    },
  };
  sizeCell(cell);
  woc.ui.tooltip(el, () => tooltipFor(found.key));
  return cell;
}

/** The anchor is the cell's own, so a pin is one thing to its list and goes down in one piece. */
function createPin(entry) {
  const cell = createCell(entry.found);
  const anchor = woc.ui.anchor3d(
    { unit: entry.found.entityId, over: 'head' },
    { className: 'woc-ew-pin' },
  );
  anchor.el.appendChild(cell.el);
  return {
    ...cell,
    destroy: () => {
      cell.destroy();
      anchor.destroy();
    },
  };
}

/** A tile is all art, so everything it says has to be in its accessible name too, the face included. */
function labelFor(found) {
  const said = `${found.rule.label}: ${found.name} on ${found.who}`;
  if (found.castBy === null) {
    return said;
  }
  return `${said}, from ${found.castBy}`;
}

/** Full rather than empty with no denominator: an empty square reads as an effect already gone. */
function sweepOf(found) {
  return fractionOf(found) ?? 1;
}

function paint(cell, entry) {
  const { found } = entry;
  sizeCell(cell);
  cell.caption.textContent = found.who;
  cell.ui.update({
    label: labelFor(found),
    icon: found.art,
    fraction: sweepOf(found),
    // `8`, or `2m` where a square has no room to spell it out, and empty for a party row,
    // whose remaining is null until the member is close enough to have one.
    value: woc.fmt.duration(found.remaining),
    count: stackCount(found),
    school: found.school,
    tone: toneOf(found),
  });
}

/** By arrival, never by remaining: sorting on remaining reorders the strip while it is being read. */
function newestFirst(a, b) {
  return b.at - a.at;
}

function ordered() {
  const rows = [...alerts.entries()].sort(([, a], [, b]) => newestFirst(a, b));
  const budget = Math.max(Math.round(woc.settings['max-tiles']), 1);
  return {
    shown: rows.slice(0, budget).map(([key, record]) => ({ key, found: record.found })),
    hidden: Math.max(rows.length - budget, 0),
  };
}

/** A party row has no entity to sit over, so it stays on the strip whatever the setting says. */
function onStrip(entry) {
  return woc.settings.placement !== 'unit' || entry.found.entityId === null;
}

/**
 * Two lists, because with a `parent` an unshown row's element is removed from the document:
 * a row that anchors itself needs a list with no parent.
 */
const strip = woc.ui.list({
  parent: list,
  key: (entry) => entry.key,
  create: (entry) => createCell(entry.found),
  update: paint,
});

const pinned = woc.ui.list({
  key: (entry) => entry.key,
  create: createPin,
  update: paint,
});

function drawOverflow(hidden) {
  if (hidden === 0) {
    overflow.textContent = '';
    return;
  }
  overflow.textContent = `+${String(hidden)} more`;
}

/** Never placed: the list inserts each square before the child at that index, so it stays last. */
function draw() {
  const { shown, hidden } = ordered();
  strip.sync(shown.filter(onStrip));
  pinned.sync(shown.filter((entry) => !onStrip(entry)));
  drawOverflow(hidden);
}

/** The pins come down too: they are outside the frame, so a hidden strip would leave them drawn. */
function blank() {
  if (strip.size === 0 && pinned.size === 0 && overflow.textContent === '') {
    return;
  }
  strip.clear();
  pinned.clear();
  overflow.textContent = '';
}

/** Both bounds are stated so the floor is one row, not however many rules were in force at first open. */
const paneBody = document.createElement('div');
paneBody.className = 'woc-ew-rules';
paneBody.style.display = 'flex';
paneBody.style.flexDirection = 'column';
paneBody.style.gap = '6px';

const pane = woc.ui.frame({
  id: 'rules',
  title: 'Emberwatch rules',
  width: PANE_WIDTH,
  height: PANE_HEIGHT,
  minWidth: PANE_MIN_WIDTH,
  minHeight: PANE_MIN_HEIGHT,
  resizable: true,
  closable: true,
  save: true,
  visible: false,
});
pane.body.appendChild(paneBody);

const paneRows = [];

function note(text) {
  const el = document.createElement('div');
  el.className = 'woc-ew-note';
  el.style.fontSize = `${String(CAPTION_FONT)}px`;
  el.style.opacity = '0.7';
  el.textContent = text;
  return el;
}

function subjectOf(rule) {
  if (rule.auraId !== null) {
    return rule.auraId;
  }
  if (rule.kind !== null) {
    return rule.kind;
  }
  if (rule.harmful === true) {
    return 'any harmful effect';
  }
  return 'any beneficial effect';
}

function describe(rule) {
  const parts = [`${rule.unit}: ${subjectOf(rule)}`, rule.on];
  if (rule.mine === true && rule.unit !== 'party') {
    parts.push('mine only');
  }
  if (rule.bout) {
    parts.push('in a bout only');
  }
  return parts.join(', ');
}

function removeRow(rule) {
  mine = mine.filter((row) => row.id !== rule.id);
  persist(STORE_ROWS, mine);
  reassemble();
  fillPane();
}

/** Only for a row the player captured. */
function removeButton(rule) {
  const button = document.createElement('button');
  button.type = 'button';
  button.className = 'woc-btn';
  button.textContent = 'Remove';
  button.addEventListener('click', () => {
    removeRow(rule);
  });
  return button;
}

function setEnabled(rule, on) {
  if (on) {
    disabled.delete(rule.id);
  } else {
    disabled.add(rule.id);
  }
  persist(STORE_OFF, [...disabled]);
  reassemble();
}

function paneRow(rule, own) {
  const el = document.createElement('div');
  el.className = 'woc-ew-rule';
  el.dataset.rule = rule.id;
  el.style.display = 'flex';
  el.style.alignItems = 'center';
  el.style.justifyContent = 'space-between';
  el.style.gap = '8px';
  const field = woc.ui.field.checkbox({
    label: rule.label,
    value: !disabled.has(rule.id),
    onChange: (on) => {
      setEnabled(rule, on);
    },
  });
  el.append(field.el, note(describe(rule)));
  if (own) {
    el.appendChild(removeButton(rule));
  }
  paneRows.push({ el, field });
  return el;
}

/** Includes rules another class owns, since a switched-off row still has to be findable. */
function paneRules() {
  const cls = playerClass();
  return [...starter, ...mine].filter((rule) => rule.forClass === 'any' || rule.forClass === cls);
}

/**
 * An empty list is three different facts: no table yet, no class yet, or nothing shipped for
 * this class. `tableRead` separates the first from the third, which otherwise look alike.
 */
function emptyReason() {
  if (!tableRead) {
    return 'The starter rules have not been read yet.';
  }
  if (playerClass() === null) {
    return 'No class yet: the starter set is picked once you are in the world.';
  }
  return 'No rules for this character yet. Capture one off your target to add the first.';
}

function fillPane() {
  for (const row of paneRows.splice(0)) {
    row.field.destroy();
    row.el.remove();
  }
  paneBody.replaceChildren();
  const rules = paneRules();
  const ownIds = new Set(mine.map((rule) => rule.id));
  if (rules.length === 0) {
    paneBody.appendChild(note(emptyReason()));
  }
  for (const rule of rules) {
    paneBody.appendChild(paneRow(rule, ownIds.has(rule.id)));
  }
  for (const line of PANE_NOTES) {
    paneBody.appendChild(note(line));
  }
}

/** Harmful first, then yours, then longest: a dot you are keeping up is what a rule is usually for. */
function priority(aura, playerId) {
  const harm = woc.world.harmful(aura);
  const ours = aura.sourceId === playerId;
  return [harm, ours, aura.remaining];
}

function betterAura(a, b, playerId) {
  const left = priority(a, playerId);
  const right = priority(b, playerId);
  for (const [at, value] of left.entries()) {
    if (value !== right[at]) {
      return value > right[at];
    }
  }
  return false;
}

function bestOnTarget() {
  const playerId = woc.world.player?.id ?? null;
  let best = null;
  for (const aura of woc.world.aurasOn('target')) {
    if (best === null || betterAura(aura, best, playerId)) {
      best = aura;
    }
  }
  return best;
}

/** `mine` is stamped from who applied it: "watch my dot" and "watch this debuff" are different rules. */
function ruleFromAura(aura, playerId) {
  return {
    id: `own-${aura.id}-${String(woc.wallClock())}`,
    label: aura.name,
    class: playerClass() ?? 'any',
    unit: 'target',
    auraId: aura.id,
    mine: aura.sourceId === playerId && playerId !== null,
    on: 'expiring',
    cue: 'buff_apply',
  };
}

function capture() {
  const aura = bestOnTarget();
  if (aura === null) {
    woc.ui.toast('Nothing on your target to watch.', { kind: 'warn' });
    return;
  }
  const rule = readRule(ruleFromAura(aura, woc.world.player?.id ?? null));
  if (rule === null) {
    woc.warn('could not turn that effect into a rule', aura);
    return;
  }
  mine = [...mine, rule];
  persist(STORE_ROWS, mine);
  reassemble();
  fillPane();
  woc.ui.toast(`Watching ${aura.name} on your target.`);
}

/** A per-character write rejects before world entry. Both callers are gestures, so this is a guard. */
async function write(key, value) {
  await woc.world.ready;
  await woc.storage.character.set(key, value);
}

/** For callers that cannot await. */
function persist(key, value) {
  write(key, value).catch((err) => {
    woc.warn(`could not save "${key}"`, err);
  });
}

/** Checked exactly as the shipped file is. */
function readStoredRules(stored) {
  if (!Array.isArray(stored)) {
    return [];
  }
  return adopt(stored, STORE_ROWS);
}

function readStoredOff(stored) {
  if (!Array.isArray(stored)) {
    return new Set();
  }
  return new Set(stored.filter((id) => typeof id === 'string'));
}

/** A per-character read waits for the character, so this settles with the rows of whoever logged in. */
async function restore() {
  const [rows, off] = await Promise.all([
    woc.storage.character.get(STORE_ROWS, null),
    woc.storage.character.get(STORE_OFF, null),
  ]);
  mine = readStoredRules(rows);
  disabled = readStoredOff(off);
  reassemble();
  fillPane();
}

function load() {
  restore().catch((err) => {
    woc.warn("could not read this character's own rules back", err);
  });
}

async function boot() {
  const rules = readFile(await woc.data(RULES_FILE));
  if (rules === null) {
    throw new Error(`${RULES_FILE} carries no "rules" array`);
  }
  starter = adopt(rules, RULES_FILE);
  tableRead = true;
  reassemble();
  fillPane();
}

// The engine runs while the strip is hidden: the cue and the banner are the half that works
// when nobody is looking at the overlay. Only the drawing is skipped.
woc.onFrame(() => {
  evaluate(woc.now());
  if (frame.visible) {
    draw();
  } else {
    blank();
  }
});

// A character switch changes both halves: the class the starter rows are picked by, and the rows.
woc.world.on('characterKey', load);

woc.keys.bind('capture', capture);

// The keybinds are spent on the two things done mid-fight, so the pane opens from the menu.
woc.ui.menuEntry({
  id: 'rules',
  label: 'Emberwatch rules',
  onClick: () => {
    pane.show();
  },
});

// Settings are read while the next frame is built, so a change lands with nothing torn down. The
// pane is the exception: its rows come from the rule set rather than from a setting.
fillPane();

boot().catch((err) => {
  woc.error('could not read the starter rules, so only your own rows will fire', err);
});

